COL = {'W':'#eef2f5','G':'#b9c3cd','D':'#5b6470','P':'#f28bb8','Y':'#ffe27a','R':'#e5484d','V':'#8e5cd9','K':'#2b2f38','L':'#cfd6de'}
rows = [r.ljust(30, '.') for r in ART.strip('\n').split('\n')]
out=[]
for y,row in enumerate(rows):
    x=0
    while x<len(row):
        c=row[x]
        if c=='.': x+=1; continue
        s=x
        while x<len(row) and row[x]==c: x+=1
        out.append(f'<rect x="{s}" y="{y}" width="{x-s}" height="1" fill="{COL[c]}"></rect>')
print(len(rows), max(len(r) for r in rows))
print('\n'.join(r.replace('.',' ') for r in rows))
open('fanny2.svgfrag','w').write(''.join(out))
